-- Ejecutar contra la BD compartida solamente una vez validado el backend.
BEGIN;

CREATE TABLE IF NOT EXISTS public.inventario_contenedores (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  lote_inventario_id integer NOT NULL REFERENCES public.lotes_inventario(id) ON DELETE RESTRICT,
  codigo varchar(100) NOT NULL,
  peso_inicial_kg numeric(18,4) NOT NULL CHECK (peso_inicial_kg > 0),
  saldo_kg numeric(18,4) NOT NULL CHECK (saldo_kg >= 0 AND saldo_kg <= peso_inicial_kg),
  ubicacion_id integer NOT NULL REFERENCES public.inventario_ubicaciones(id) ON DELETE RESTRICT,
  estado varchar(24) NOT NULL DEFAULT 'POR_VERIFICAR'
    CHECK (estado IN ('POR_VERIFICAR','VERIFICADO','INCIDENCIA','AGOTADO')),
  verificado_por varchar(100),
  verificado_en timestamptz,
  creado_en timestamptz NOT NULL DEFAULT now(),
  UNIQUE (lote_inventario_id,codigo)
);
CREATE INDEX IF NOT EXISTS idx_contenedores_lote_ubicacion
  ON public.inventario_contenedores(lote_inventario_id,ubicacion_id,estado);

CREATE TABLE IF NOT EXISTS public.contenedor_movimientos (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  contenedor_id integer NOT NULL REFERENCES public.inventario_contenedores(id) ON DELETE RESTRICT,
  movimiento_inventario_id integer REFERENCES public.movimientos_inventario("id_Movi_Invent") ON DELETE RESTRICT,
  tipo varchar(32) NOT NULL CHECK (tipo IN ('RECEPCION','PRODUCCION','APERTURA','CONSUMO','DESPACHO','RETORNO','CONCILIACION')),
  cantidad numeric(18,4) NOT NULL CHECK (cantidad > 0),
  actor varchar(100) NOT NULL,
  observaciones text,
  creado_en timestamptz NOT NULL DEFAULT now(),
  UNIQUE (contenedor_id,movimiento_inventario_id)
);
CREATE INDEX IF NOT EXISTS idx_movcontenedor_cont_fecha ON public.contenedor_movimientos(contenedor_id,creado_en);

CREATE TABLE IF NOT EXISTS public.calidad_conciliaciones_legacy (
  lote_produccion_id integer PRIMARY KEY REFERENCES public.lotes_produccion("id_Lote_Produccion") ON DELETE RESTRICT,
  estado varchar(20) NOT NULL DEFAULT 'PENDIENTE' CHECK (estado IN ('PENDIENTE','VALIDADA','BLOQUEADA')),
  motivo text,
  documento_nombre varchar(255),
  documento_mime varchar(100),
  documento_contenido bytea,
  revisado_por varchar(100),
  revisado_en timestamptz,
  creado_en timestamptz NOT NULL DEFAULT now()
);
-- Solo marca para revisión: nunca acredita/certifica de forma automática los lotes anteriores.
INSERT INTO public.calidad_conciliaciones_legacy(lote_produccion_id)
SELECT lp."id_Lote_Produccion" FROM public.lotes_produccion lp
WHERE lp.estado='FINALIZADO' AND lp."estado_Calida"='LIBERADO'
AND NOT EXISTS (SELECT 1 FROM public.certificado_calidad c WHERE c.lote_id=lp."id_Lote_Produccion"
  AND c.estatus='EMITIDO' AND c."estatus_Calidad"='APROBADO' AND c.documento_contenido IS NOT NULL)
ON CONFLICT (lote_produccion_id) DO NOTHING;

CREATE TABLE IF NOT EXISTS public.vehiculos_logistica (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  placa varchar(30) NOT NULL UNIQUE,
  tipo varchar(12) NOT NULL CHECK (tipo IN ('TORTON','TRAILER')),
  capacidad_contenedores integer NOT NULL CHECK (capacidad_contenedores IN (12,22)),
  capacidad_kg numeric(18,4) NOT NULL CHECK (capacidad_kg > 0),
  transportista varchar(150),
  activo boolean NOT NULL DEFAULT true,
  creado_en timestamptz NOT NULL DEFAULT now(),
  CHECK ((tipo='TORTON' AND capacidad_contenedores=12) OR
         (tipo='TRAILER' AND capacidad_contenedores=22))
);

CREATE TABLE IF NOT EXISTS public.viajes_logistica (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  folio varchar(100) NOT NULL UNIQUE,
  vehiculo_id integer NOT NULL REFERENCES public.vehiculos_logistica(id) ON DELETE RESTRICT,
  operador varchar(150) NOT NULL,
  estado varchar(24) NOT NULL DEFAULT 'PROGRAMADO'
    CHECK (estado IN ('PROGRAMADO','CARGADO','DESPACHADO','ENTREGADO','CANCELADO')),
  fecha_programada timestamptz,
  fecha_salida timestamptz,
  fecha_cierre timestamptz,
  observaciones text,
  creado_por varchar(100) NOT NULL,
  creado_en timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS idx_viajes_estado_fecha ON public.viajes_logistica(estado,fecha_programada);

ALTER TABLE public.entregas_logistica ADD COLUMN IF NOT EXISTS viaje_id integer;
DO $$
BEGIN
  IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname='fk_entregas_logistica_viaje') THEN
    ALTER TABLE public.entregas_logistica
      ADD CONSTRAINT fk_entregas_logistica_viaje FOREIGN KEY (viaje_id)
      REFERENCES public.viajes_logistica(id) ON DELETE RESTRICT;
  END IF;
END $$;
CREATE INDEX IF NOT EXISTS idx_entregas_viaje ON public.entregas_logistica(viaje_id);

CREATE TABLE IF NOT EXISTS public.entrega_contenedores (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  entrega_material_id integer NOT NULL REFERENCES public.entrega_materiales(id) ON DELETE RESTRICT,
  contenedor_id integer NOT NULL REFERENCES public.inventario_contenedores(id) ON DELETE RESTRICT,
  cantidad_kg numeric(18,4) NOT NULL CHECK (cantidad_kg > 0),
  creado_en timestamptz NOT NULL DEFAULT now(),
  UNIQUE (entrega_material_id,contenedor_id)
);
CREATE INDEX IF NOT EXISTS idx_entrega_cont_activa ON public.entrega_contenedores(contenedor_id);

CREATE TABLE IF NOT EXISTS public.logistica_eventos (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  entrega_id integer REFERENCES public.entregas_logistica("id_Entrega") ON DELETE RESTRICT,
  viaje_id integer REFERENCES public.viajes_logistica(id) ON DELETE RESTRICT,
  accion varchar(80) NOT NULL,
  actor varchar(100) NOT NULL,
  datos jsonb,
  creado_en timestamptz NOT NULL DEFAULT now(),
  CHECK (entrega_id IS NOT NULL OR viaje_id IS NOT NULL)
);
CREATE INDEX IF NOT EXISTS idx_logistica_eventos_entrega ON public.logistica_eventos(entrega_id,creado_en);

